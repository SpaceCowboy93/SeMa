import { test, expect } from '@playwright/test'

test('shared trip planning survives reload, clears optional fields and deletes cleanly on mobile', async ({ page, context }, testInfo) => {
  const external: string[] = []
  await context.route('**/*', route => {
    if (new URL(route.request().url()).origin === 'http://127.0.0.1:3215') return route.continue()
    external.push(new URL(route.request().url()).hostname); return route.abort()
  })
  await page.goto('/dev-preview/trips')
  await page.getByRole('button', { name: 'Plan a trip' }).click()
  await page.getByLabel('Trip name', { exact: true }).fill('Our mobile escape')
  await page.keyboard.press('Tab'); await expect(page.getByLabel('Destination', { exact: true })).toBeFocused()
  await page.getByLabel('Destination', { exact: true }).fill('Porto')
  await page.getByLabel('Country', { exact: true }).fill('Portugal')
  await page.getByLabel('Start date', { exact: true }).fill('2027-06-01')
  await page.getByRole('button', { name: 'Save trip', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Our mobile escape' })).toBeVisible()
  await page.getByRole('button', { name: 'Add to packing checklist' }).click()
  await page.getByLabel('Item name', { exact: true }).fill('Passport')
  await page.getByRole('button', { name: 'Save item', exact: true }).click()
  await page.getByRole('checkbox', { name: 'Complete Passport', exact: true }).check()
  await page.getByRole('button', { name: 'Add to itinerary & places' }).click()
  await page.getByLabel('Item name', { exact: true }).fill('Museum')
  await page.getByLabel('Date', { exact: true }).fill('2027-06-01')
  await page.getByLabel('Estimated price', { exact: true }).fill('20')
  await page.getByLabel('Actual spending', { exact: true }).fill('0')
  await page.getByRole('button', { name: 'Save item', exact: true }).click()
  await expect(page.getByRole('heading', { name: '2027-06-01', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Edit trip details' }).click()
  await page.getByLabel('Start date', { exact: true }).fill('')
  await page.getByRole('button', { name: 'Save trip', exact: true }).click()
  await page.reload()
  await page.getByRole('button', { name: 'Open Our mobile escape' }).click()
  await expect(page.getByRole('checkbox', { name: 'Complete Passport', exact: true })).toBeChecked()
  await expect(page.getByText('Dates to come · idea', { exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath(`trips-${testInfo.project.name}.png`), fullPage: true })
  await page.getByRole('button', { name: 'Delete trip', exact: true }).click()
  await page.getByRole('button', { name: 'Delete trip permanently' }).click()
  await page.reload()
  await expect(page.getByRole('button', { name: 'Open Our mobile escape' })).toHaveCount(0)
  await expect(page.getByRole('heading', { name: 'Where shall we go?' })).toBeVisible()
  expect(external).toEqual([])
})
